# Operator perbandingan membandingkan dua nilai dan menghasilkan boolean: True atau False.
# Operator ini sering digunakan bersama if untuk menentukan cabang yang dijalankan.

# SAMA DENGAN (==)
# Menghasilkan True jika kedua nilai sama persis.
print(5 == 5)   # True

# TIDAK SAMA DENGAN (!=)
# Menghasilkan True jika kedua nilai tidak sama.
print(4 != 6)   # True

# LEBIH BESAR DARI (>)
# Menghasilkan True jika nilai kiri lebih besar dari nilai kanan.
print(5 > 6)    # False

# LEBIH BESAR SAMA DENGAN (>=)
# Menghasilkan True jika nilai kiri lebih besar dari atau sama dengan nilai kanan.
print(5 >= 5)   # True

# LEBIH KECIL DARI (<)
# Menghasilkan True jika nilai kiri lebih kecil dari nilai kanan.
print(4 < 5)    # True

# LEBIH KECIL SAMA DENGAN (<=)
# Menghasilkan True jika nilai kiri lebih kecil dari atau sama dengan nilai kanan.
print(-1 <= 0)  # True