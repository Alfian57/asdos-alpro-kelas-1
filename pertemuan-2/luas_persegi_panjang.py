# Variabel panjang menyimpan ukuran panjang persegi panjang.
panjang = 25

# Variabel lebar menyimpan ukuran lebar persegi panjang.
lebar = 10

# Luas persegi panjang dihitung dengan mengalikan panjang dan lebar.
luas = panjang * lebar

# Tampilkan hasil perhitungan luas ke layar.
print("Luas persegi panjang:", luas)
