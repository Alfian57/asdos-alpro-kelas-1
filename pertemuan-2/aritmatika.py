# Setiap kelompok operator berisi contoh lengkap dengan keterangan dan contoh sederhana.
# Pada contoh lengkap, print() menampilkan teks keterangan dan hasil perhitungan.
s
# PENJUMLAHAN (+)
# Contoh lengkap: tampilkan keterangan dan hasil 5 + 5.
print("Penjumlahan 5 + 5:", 5 + 5)

# Contoh sederhana: jumlahkan 8 dan 2, lalu tampilkan hasilnya.
print(8 + 2)



# PENGURANGAN (-)
# Contoh lengkap: tampilkan keterangan dan hasil 10 - 4.
print("Pengurangan 10 - 4:", 10 - 4)

# Contoh sederhana: kurangi 7 dari 15, lalu tampilkan hasilnya.
print(15 - 7)



# PERKALIAN (*)
# Contoh lengkap: tampilkan keterangan dan hasil 14 * 3.
print("Perkalian 14 * 3:", 14 * 3)

# Contoh sederhana: kalikan 6 dengan 5, lalu tampilkan hasilnya.
print(6 * 5)



# PEMBAGIAN (/)
# Contoh lengkap: tampilkan keterangan dan hasil 10 / 2.
print("Pembagian 10 / 2:", 10 / 2)

# Contoh sederhana: bagi 9 dengan 2, lalu tampilkan hasilnya.
print(9 / 2)



# PEMBAGIAN BULAT (//)
# Operator // membulatkan hasil pembagian ke bawah.
# Contoh lengkap: tampilkan keterangan dan hasil 10 // 3.
print("Pembagian bulat 10 // 3:", 10 // 3)

# Contoh sederhana: bagi 20 dengan 6 menggunakan operator pembagian bulat.
print(20 // 6)



# SISA BAGI (%)
# Contoh lengkap: tampilkan keterangan dan sisa pembagian 10 % 3.
print("Sisa bagi 10 % 3:", 10 % 3)

# Contoh sederhana: tampilkan sisa pembagian 14 dengan 5.
print(14 % 5)



# PERPANGKATAN (**)
# Contoh lengkap: tampilkan keterangan dan hasil 2 pangkat 3.
print("Perpangkatan 2 ** 3:", 2 ** 3)
# Contoh sederhana: hitung 5 pangkat 2, lalu tampilkan hasilnya.
print(5 ** 2)
