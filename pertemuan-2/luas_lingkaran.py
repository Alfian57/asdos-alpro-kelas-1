# Nilai phi yang digunakan pada latihan ini adalah 3.14.
phi = 3.14

# Jari-jari lingkaran dalam satuan yang sama dengan satuan luas hasilnya.
jari_jari = 7

# Rumus luas lingkaran adalah phi dikali jari-jari pangkat dua.
luas_lingkaran = phi * jari_jari ** 2

# Tampilkan hasil perhitungan luas lingkaran.
print(luas_lingkaran)
