# Berkas Python berekstensi .py berisi instruksi yang dijalankan oleh Python.
# Tanda # memulai komentar; komentar menjelaskan kode dan tidak dijalankan.
# Tanda = memberikan nilai di sebelah kanan kepada variabel di sebelah kiri.

# STRING (str)
# String adalah teks yang ditulis di antara tanda petik yang berpasangan.
# Petik satu ('...') dan petik dua ("...") sama-sama boleh digunakan.
# Teks harus dimulai dan diakhiri dengan jenis petik yang sama.
nama = "Alfian Gading Saputra"

# Contoh string lain yang menggunakan petik satu.
mata_kuliah = 'Algoritma Pemrograman'

# INTEGER (int)
# Integer adalah bilangan bulat tanpa titik desimal.
# Bilangan bulat dapat positif atau negatif; tanda minus ditulis di depan angka.
umur = 22
perubahan_skor = -5

# FLOAT (float)
# Float adalah bilangan desimal dan menggunakan titik, bukan koma, sebagai pemisah desimal.
# Float juga dapat bernilai negatif dengan tanda minus di depan angka.
berat_badan = 50.3
perubahan_suhu = -2.5

# Angka ditulis tanpa tanda petik agar dikenali sebagai angka, bukan sebagai string.
# Contoh: 5 adalah integer, sedangkan 5.0 adalah float.

# BOOLEAN (bool)
# Boolean hanya memiliki dua nilai: True dan False.
# Huruf pertama T pada True dan F pada False harus kapital; huruf lainnya kecil.
# Nilai boolean tidak ditulis di antara tanda petik.
mahasiswa_aktif = True
sudah_lulus = False

# Nama variabel tidak boleh mengandung spasi atau diawali angka; gunakan garis bawah
# untuk memisahkan kata, misalnya berat_badan.
# Python membedakan huruf besar dan kecil, jadi nama dan Nama dianggap berbeda.

# Fungsi print() menampilkan teks langsung ke layar.
print("Selamat datang")

# Tampilkan nilai string yang disimpan dalam variabel nama.
print(nama)

# Tampilkan nilai string yang disimpan dalam variabel mata_kuliah.
print(mata_kuliah)

# Tampilkan nilai integer positif yang disimpan dalam variabel umur.
print(umur)

# Tampilkan contoh integer negatif.
print(perubahan_skor)

# Tampilkan nilai float positif yang disimpan dalam variabel berat_badan.
print(berat_badan)

# Tampilkan contoh float negatif.
print(perubahan_suhu)

# Tampilkan contoh nilai boolean True.
print(mahasiswa_aktif)

# Tampilkan contoh nilai boolean False.
print(sudah_lulus)
