# Perulangan while menjalankan blok kode berulang kali selama kondisinya bernilai True.
# Pola perulangan memiliki nilai awal, kondisi, dan perubahan nilai agar perulangan dapat berhenti.

# Inisialisasi nilai awal.
angka = 1
print(angka)

# Perulangan berjalan selama nilai angka kurang dari atau sama dengan 5.
while angka <= 5:
    # Nilai angka ditambah 1 pada setiap perulangan agar kondisi berhenti tercapai.
    angka = angka + 1
    print(angka)