# Contoh perulangan while dengan penambahan nilai sebesar 2 (deret genap).

# Inisialisasi nilai awal mulai dari 0.
angka = 0
print(angka)

# Perulangan berjalan selama nilai angka kurang dari atau sama dengan 5.
while angka <= 5:
    # Nilai angka bertambah 2 pada setiap perulangan.
    angka = angka + 2
    print(angka)