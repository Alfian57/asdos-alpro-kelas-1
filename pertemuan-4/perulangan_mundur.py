# Contoh perulangan while mundur (countdown) menggunakan pengurangan nilai.

# Inisialisasi nilai awal mulai dari 10.
angka = 10
print(angka)

# Perulangan berjalan selama nilai angka lebih dari atau sama dengan 0.
while angka >= 0:
    # Nilai angka dikurangi 1 pada setiap perulangan.
    angka = angka - 1
    print(angka)