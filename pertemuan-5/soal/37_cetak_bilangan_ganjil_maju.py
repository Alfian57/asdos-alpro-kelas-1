# Soal 37: Cetak Bilangan Ganjil Maju
# Cerita: Mahasiswa diminta membuat program yang menampilkan deret bilangan
# ganjil positif dari angka 1 sampai kurang dari 20.
# Spesifikasi:
# - Inisialisasi variabel bilangan = 1.
# - Gunakan perulangan while bilangan < 20.
# - Tampilkan nilai bilangan ke layar.
# - Tambahkan nilai bilangan sebanyak 2 pada setiap iterasi.


bilangan = 1

while bilangan < 20:
    print(bilangan)
    bilangan += 2
