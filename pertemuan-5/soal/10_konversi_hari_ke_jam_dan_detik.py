# Cerita: Sebuah proyek kampus direncanakan selesai dalam waktu 3 hari. Mahasiswa
# ingin mengetahui berapa total jam dan total detik dari durasi tersebut.
# Spesifikasi:
# - Buat variabel jumlah_hari bernilai 3.
# - Hitung total jam (jumlah_hari * 24) ke dalam variabel total_jam.
# - Hitung total detik (total_jam * 3600) ke dalam variabel total_detik.
