# Soal 32: Deret Kelipatan Empat
# Cerita: Seorang anak ingin mencatat bilangan kelipatan 4 mulai dari angka 4 hingga
# batas maksimal 40.
# Spesifikasi:
# - Inisialisasi variabel angka = 4.
# - Gunakan perulangan while angka <= 40 untuk mencetak nilai angka.
# - Tambahkan nilai angka sebesar 4 pada setiap iterasi.


angka = 4

while angka <= 40:
    print(angka)
    angka += 4
