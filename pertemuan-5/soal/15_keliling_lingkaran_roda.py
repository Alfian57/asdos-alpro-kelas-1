# Soal 15: Keliling Lingkaran Roda
# Cerita: Sebuah roda sepeda anak memiliki jari-jari 14 cm. Pengrajin sepeda ingin
# menghitung keliling roda menggunakan nilai pendekatan pi 3.14.
# Spesifikasi:
# - Buat variabel jari_jari bernilai 14.0 dan pi bernilai 3.14.
# - Hitung keliling roda dengan rumus 2 * pi * jari_jari ke dalam variabel
# keliling_roda.
# - Tampilkan nilai keliling_roda ke layar.


jari_jari = 14.0
pi = 3.14
keliling_roda = 2 * pi * jari_jari
print(keliling_roda)
