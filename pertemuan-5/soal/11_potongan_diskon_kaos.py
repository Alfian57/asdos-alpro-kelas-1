# Soal 11: Potongan Diskon Kaos
# Cerita: Sebuah toko pakaian memberikan diskon 15% untuk sehelai kaos seharga
# Rp120.000. Pembeli ingin menghitung nominal potongan harga yang didapatkan.
# Spesifikasi:
# - Buat variabel harga_kaos bernilai 120000 dan persen_diskon bernilai 0.15.
# - Hitung nilai potongan diskon dengan rumus harga_kaos * persen_diskon ke
# dalam variabel potongan_harga.
# - Tampilkan nilai potongan_harga ke layar.


harga_kaos = 120000
persen_diskon = 0.15
potongan_harga = harga_kaos * persen_diskon
print(potongan_harga)
