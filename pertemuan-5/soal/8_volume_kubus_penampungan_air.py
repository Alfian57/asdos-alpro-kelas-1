# Soal 8: Volume Kubus Penampungan Air
# Cerita: Sebuah bak mandi penampungan air berbentuk kubus sempurna dengan
# panjang rusuk 90 cm. Pemilik rumah ingin menghitung volume tampung bak tersebut.
# Spesifikasi:
# - Buat variabel rusuk bernilai 90.
# - Hitung volume dengan operasi pangkat tiga (rusuk ** 3) ke dalam variabel
# volume_kubus.
# - Tampilkan nilai volume_kubus ke layar.


rusuk = 90
volume_kubus = rusuk ** 3
print(volume_kubus)
