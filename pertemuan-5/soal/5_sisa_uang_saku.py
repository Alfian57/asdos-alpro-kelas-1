# Soal 5: Sisa Uang Saku
# Cerita: Rian memiliki uang saku mingguan sebesar Rp150.000. Selama seminggu, ia
# telah mengeluarkan uang sebesar Rp85.000 untuk makan dan Rp20.000 untuk
# fotokopi materi kuliah.
# Spesifikasi:
# - Buat variabel uang_saku bernilai 150000, biaya_makan bernilai 85000, dan
# biaya_fotokopi bernilai 20000.
# - Hitung sisa uang dengan mengurangkan uang saku dengan total pengeluaran
# ke dalam variabel sisa_uang.
# - Tampilkan nilai sisa_uang ke layar.


uang_saku = 150000
biaya_makan = 85000
biaya_fotokopi = 20000
sisa_uang = uang_saku - (biaya_makan + biaya_fotokopi)
print(sisa_uang)
