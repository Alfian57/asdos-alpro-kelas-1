# Soal 31: Hitung Mundur Peluncuran
# Cerita: Pusat sains membuat simulasi hitung mundur peluncuran roket sederhana dari
# angka 5 sampai 1, diakhiri dengan seruan peluncuran.
# Spesifikasi:
# - Inisialisasi variabel hitung = 5.
# - Gunakan perulangan while hitung >= 1 untuk mencetak nilai hitung.
# - Kurangi nilai hitung sebanyak 1 pada setiap iterasi.
# - Setelah perulangan selesai, cetak teks "Roket Meluncur!".


hitung = 5

while hitung >= 1:
    print(hitung)
    hitung -= 1

print("Roket Meluncur!")
