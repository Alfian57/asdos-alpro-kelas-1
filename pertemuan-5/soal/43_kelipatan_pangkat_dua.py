# Soal 43: Kelipatan Pangkat Dua
# Cerita: Program sains komputer menampilkan deret perpangkatan dua mulai dari 1,
# 2, 4, 8, hingga batas nilai di bawah 100.
# Spesifikasi:
# - Inisialisasi variabel nilai = 1.
# - Gunakan while nilai < 100.
# - Tampilkan nilai nilai saat ini.
# - Kalikan nilai dengan 2 pada setiap iterasi (nilai = nilai * 2).


nilai = 1

while nilai < 100:
    print(nilai)
    nilai = nilai * 2
