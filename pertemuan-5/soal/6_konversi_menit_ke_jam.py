# Soal 6: Konversi Menit ke Jam
# Cerita: Sebuah film dokumenter memiliki durasi total 145 menit. Penonton ingin
# mengetahui durasi tersebut dalam format jam dan sisa menit.
# Spesifikasi:
# - Buat variabel total_menit bernilai 145.
# - Hitung jumlah jam menggunakan pembagian bulat dengan 60 (// 60) ke dalam
# variabel jam.
# - Hitung sisa menit menggunakan operator modulus dengan 60 (% 60) ke dalam
# variabel sisa_menit.
# - Tampilkan nilai jam dan sisa_menit ke layar.


total_menit = 145
jam = total_menit // 60
sisa_menit = total_menit % 60
print(jam)
print(sisa_menit)
