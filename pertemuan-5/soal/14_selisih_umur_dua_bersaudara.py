# Soal 14: Selisih Umur Dua Bersaudara
# Cerita: Andi berumur 21 tahun dan adiknya berumur 14 tahun. Mereka ingin
# mengetahui berapa selisih umur di antara keduanya.
# Spesifikasi:
# - Buat variabel umur_kakak bernilai 21 dan umur_adik bernilai 14.
# - Hitung selisih umur dengan rumus umur_kakak - umur_adik ke dalam variabel
# selisih_umur.
# - Tampilkan nilai selisih_umur ke layar.


