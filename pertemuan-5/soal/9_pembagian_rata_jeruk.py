# Soal 9: Pembagian Rata Jeruk
# Cerita: Paman memanen 50 kg jeruk dan ingin membaginya secara merata ke dalam
# 4 keranjang buah tanpa menyisakan jeruk.
# Spesifikasi:
# - Buat variabel total_panen bernilai 50.0 dan jumlah_keranjang bernilai 4.
# - Hitung berat jeruk per keranjang menggunakan pembagian riil (/) ke dalam
# variabel berat_per_keranjang.
# - Tampilkan nilai berat_per_keranjang ke layar.


total_panen = 50.0
jumlah_keranjang = 4
berat_per_keranjang = total_panen / jumlah_keranjang
print(berat_per_keranjang)
