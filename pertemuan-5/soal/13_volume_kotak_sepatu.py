# Soal 13: Volume Kotak Sepatu
# Cerita: Sebuah pabrik memproduksi kotak sepatu berbentuk balok dengan panjang 30
# cm, lebar 18 cm, dan tinggi 12 cm.
# Spesifikasi:
# - Buat variabel panjang bernilai 30, lebar bernilai 18, dan tinggi bernilai 12.
