# Soal 12: Iuran Listrik Kamar Kos
# Cerita: Tagihan listrik rumah kos bulan ini adalah Rp360.000. Biaya tersebut akan
# dibagi rata secara bulat kepada 5 orang penghuni kos.
# Spesifikasi:
# - Buat variabel total_tagihan bernilai 360000 dan jumlah_penghuni bernilai 5.
# - Hitung tagihan per orang menggunakan pembagian bulat (//) ke dalam variabel
# tagihan_per_orang.
# - Tampilkan nilai tagihan_per_orang ke layar.


total_tagihan = 360000
jumlah_penghuni = 5
tagihan_per_orang = total_tagihan // jumlah_penghuni
print(tagihan_per_orang)
