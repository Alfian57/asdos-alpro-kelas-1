# Soal 66: Cetak Nomor Kupon Undian
# Cerita: Panitia acara kampus ingin mencetak nomor urut kupon undian mulai dari nomor 1
# hingga nomor 5 secara berurutan menggunakan perulangan for.
# Spesifikasi:
# - Gunakan perulangan for nomor in range(1, 6):.
# - Di dalam perulangan, tampilkan teks "Kupon Undian ke-{nomor}" menggunakan
# f-string.


for nomor in range(1, 6):
    print(f"Kupon Undian ke-{nomor}")
